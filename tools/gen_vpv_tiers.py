"""Generate the VP-V Config data table from docs/design/vpv-tiers.json + docs/design/slots.json.

    python -I tools/gen_vpv_tiers.py           # writes src/VP-V/config/VpvTierTable.generated.h
    python -I tools/gen_vpv_tiers.py --check   # exit 1 when the header is stale or a reference is wrong

Checks: every unit slot exists in slots.json; every slot in the pixel path (order < 900) and the
projector control belongs to exactly one unit; tier names are the global tiers in order; preset
'set'/'on_enter' keys and toggle keys have a built-in default in 'defaults'; a toggle key is never
also a preset key (toggling it would turn every tier into Custom); planned keys are slots.json
planned_keys of their slot.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TIERS = ROOT / "docs" / "design" / "vpv-tiers.json"
SLOTS = ROOT / "docs" / "design" / "slots.json"
OUT = ROOT / "src" / "VP-V" / "config" / "VpvTierTable.generated.h"


def c(s):
    if s is None:
        return "nullptr"
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def validate(tiers, slots):
    errors = []
    by_id = {s["id"]: s for s in slots["slots"]}
    global_tiers = slots["tiers"]
    defaults = tiers["defaults"]
    owner = {}
    for u in tiers["units"]:
        for sid in u["slots"]:
            if sid not in by_id:
                errors.append(f"unit {u['id']}: unknown slot {sid}")
            elif sid in owner:
                errors.append(f"slot {sid} in units {owner[sid]} and {u['id']}")
            owner[sid] = u["id"]
        names = u["tiers"]
        if names != [t for t in global_tiers if t in names]:
            errors.append(f"unit {u['id']}: tiers {names} not in global order {global_tiers}")
        if set(u["presets"]) != set(names):
            errors.append(f"unit {u['id']}: presets {sorted(u['presets'])} != tiers {names}")
        toggle_keys = {t["key"] for t in u.get("toggles", [])}
        for tier, p in u["presets"].items():
            for k in p["set"]:
                if k not in defaults:
                    errors.append(f"{u['id']}.{tier}: key {k} has no default")
                if k in toggle_keys:
                    errors.append(f"{u['id']}.{tier}: key {k} is also a toggle")
            for e in p.get("on_enter", []):
                if e["key"] not in defaults:
                    errors.append(f"{u['id']}.{tier}: on_enter key {e['key']} has no default")
        for t in u.get("toggles", []):
            if t["key"] not in defaults:
                errors.append(f"{u['id']}: toggle {t['key']} has no default")
            if t["slot"] not in u["slots"]:
                # a toggle may sit with the unit that owns its effect (render_ahead under motion)
                if t["slot"] not in by_id:
                    errors.append(f"{u['id']}: toggle {t['key']} unknown slot {t['slot']}")
        for p in u.get("planned", []):
            s = by_id.get(p["slot"])
            if not s:
                errors.append(f"{u['id']}: planned {p['key']} unknown slot {p['slot']}")
            elif p["key"] not in s.get("planned_keys", []):
                errors.append(f"{u['id']}: planned {p['key']} not in {p['slot']}.planned_keys")
    for s in slots["slots"]:
        if (s["order"] < 900 or s["unit"] == "drive") and s["id"] not in owner:
            errors.append(f"slot {s['id']} belongs to no VP-V unit")
    retirement = tiers.get("proposed_retirement", {})
    seen = set()
    for r in retirement.get("keys", []):
        if r["group"] not in retirement.get("groups", {}):
            errors.append(f"retirement {r['key']}: unknown group {r['group']}")
        if r["section"] not in ("vprenderer", "general", "led_drive", "projector", "queue"):
            errors.append(f"retirement {r['key']}: unknown section {r['section']}")
        if (r["section"], r["key"]) in seen:
            errors.append(f"retirement {r['key']} listed twice")
        seen.add((r["section"], r["key"]))
    return errors


def generate(tiers, slots):
    out = []
    w = out.append
    w("// GENERATED by tools/gen_vpv_tiers.py from docs/design/vpv-tiers.json + docs/design/slots.json.")
    w("// Do not edit: change the JSON and re-run the generator (the Config tests check it is current).")
    w("#pragma once")
    w('#include "VpvTierModel.h"')
    w("")
    w("namespace Vpv")
    w("{")
    w("    inline const Table& TierTable()")
    w("    {")
    w("        static const Table table = []")
    w("        {")
    w("            Table t;")
    w(f"            t.slotsFrozen = {c(slots.get('frozen'))};")
    for g in slots["tiers"]:
        w(f"            t.tiers.push_back({c(g)});")
    vs = tiers["vpv_section"]
    w(f"            t.section = {c(vs['section'])}; t.pathwayKey = {c(vs['pathway_key'])}; t.pathwayDefault = {c(vs['pathway_default'])};")
    d = tiers["delay"]
    w(f"            t.delaySection = {c(d['section'])}; t.delayKey = {c(d['key'])}; t.recommendedFrames = {int(d['recommended_frames'])};")
    for k, v in tiers["defaults"].items():
        w(f"            t.defaults.push_back({{ {c(k)}, {c(v)} }});")
    for s in slots["slots"]:
        fb = (s.get("fallback") or {}).get("entry")
        w(f"            t.slotList.push_back({{ {c(s['id'])}, {c(s['name'])}, {c(s['unit'])}, {c(s['status'])}, {int(s['order'])}, {c(fb)} }});")
    for u in tiers["units"]:
        w("            {")
        w("                Unit u;")
        w(f"                u.id = {c(u['id'])}; u.name = {c(u['name'])}; u.summary = {c(u['summary'])};")
        w(f"                u.untieredReason = {c(u.get('untiered_reason'))};")
        w(f"                u.more = {c(u.get('more_settings'))};")
        for sid in u["slots"]:
            w(f"                u.slotIds.push_back({c(sid)});")
        for tier in u["tiers"]:
            p = u["presets"][tier]
            w("                {")
            w(f"                    Preset p; p.tier = {c(tier)}; p.description = {c(p['description'])}; p.cost = {c(p.get('cost'))};")
            for k, v in p["set"].items():
                w(f"                    p.set.push_back({{ {c(k)}, {c(v)} }});")
            for e in p.get("on_enter", []):
                w(f"                    p.onEnter.push_back({{ {c(e['key'])}, {c(e['from'])}, {c(e['to'])} }});")
            w("                    u.presets.push_back(p);")
            w("                }")
        for tier, note in u.get("planned_tiers", {}).items():
            w(f"                u.plannedTiers.push_back({{ {c(tier)}, {c(note)} }});")
        for k in u.get("taste", []):
            w(f"                u.taste.push_back({c(k)});")
        for t in u.get("toggles", []):
            vals = ", ".join(c(v) for v in t["values"])
            w(f"                u.toggles.push_back({{ {c(t['key'])}, {c(t['label'])}, {{ {vals} }}, {c(t['slot'])} }});")
        for p in u.get("planned", []):
            w(f"                u.planned.push_back({{ {c(p['key'])}, {c(p['label'])}, {c(p['slot'])} }});")
        w("                t.units.push_back(u);")
        w("            }")
    retirement = tiers.get("proposed_retirement", {})
    if retirement:
        w(f"            t.retirementNote = {c(retirement.get('note'))};")
        for g, title in retirement.get("groups", {}).items():
            w(f"            t.retirementGroups.push_back({{ {c(g)}, {c(title)} }});")
        for r in retirement.get("keys", []):
            w(f"            t.retirements.push_back({{ {c(r['section'])}, {c(r['key'])}, {c(r['group'])}, {c(r['reason'])} }});")
    w("            return t;")
    w("        }();")
    w("        return table;")
    w("    }")
    w("}")
    return "\n".join(out) + "\n"


def main():
    tiers = json.loads(TIERS.read_text(encoding="utf-8"))
    slots = json.loads(SLOTS.read_text(encoding="utf-8"))
    errors = validate(tiers, slots)
    for e in errors:
        print("ERROR:", e)
    text = generate(tiers, slots)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"STALE: {OUT.relative_to(ROOT)} (run python -I tools/gen_vpv_tiers.py)")
            return 1
        return 1 if errors else 0
    if errors:
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
