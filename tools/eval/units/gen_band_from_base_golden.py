"""Generates repair/grain_split/tests/BandFromBaseGolden.generated.h from band_from_base_ref.py.

Run:  python -I tools/eval/units/gen_band_from_base_golden.py
Deterministic: values written with %.17g, fixed order.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import band_from_base_ref as ref  # noqa: E402

OUT = os.path.normpath(os.path.join(
    HERE, "..", "..", "..", "src", "VP-V", "modules", "repair", "grain_split", "tests",
    "BandFromBaseGolden.generated.h"))
SIGMAS = (0.8, 1.0, 1.3, 2.5, 6.0)
W, H = 9, 7
PLANE = [float((x * 7 + y * 13) % 17) for y in range(H) for x in range(W)]


def arr(vals):
    return ", ".join("%.17g" % v for v in vals)


def main():
    L = ["// Copyright(C) 2026 VP-V contributors", "// SPDX-License-Identifier: GPL-3.0-only", "//",
         "// GENERATED by tools/eval/units/gen_band_from_base_golden.py from band_from_base_ref.py. Do not edit.",
         "#pragma once", "", "namespace BandFromBaseGolden", "{",
         "\tconstexpr int kSigmaCount = %d;" % len(SIGMAS),
         "\tconstexpr double kSigmas[kSigmaCount] = { %s };" % arr(SIGMAS),
         "\tconstexpr int kRadius[kSigmaCount] = { %s };" % ", ".join(str(ref.radius(s)) for s in SIGMAS),
         "\tconstexpr double kHalfSigma[kSigmaCount] = { %s };" % arr([ref.half_sigma(s) if s > 0.5 else 0.0 for s in SIGMAS])]
    for i, s in enumerate(SIGMAS):
        r = ref.radius(s)
        L.append("\tconstexpr double kWeights%d[%d] = { %s };" % (
            i, 2 * r + 1, arr([ref.weight(k, s, r) for k in range(-r, r + 1)])))
    L.append("\tconstexpr const double* kWeights[kSigmaCount] = { %s };" % ", ".join(
        "kWeights%d" % i for i in range(len(SIGMAS))))
    L.append("\tconstexpr int kPlaneW = %d, kPlaneH = %d;" % (W, H))
    L.append("\tconstexpr double kPlane[kPlaneW * kPlaneH] = { %s };" % arr(PLANE))
    for name, s in (("A", 1.3), ("B", 0.8)):
        L.append("\tconstexpr double kBlurSigma%s = %.17g;" % (name, s))
        L.append("\tconstexpr double kBlur%s[kPlaneW * kPlaneH] = { %s };" % (name, arr(ref.blur(PLANE, W, H, s))))
    L.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
