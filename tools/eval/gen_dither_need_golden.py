"""Generates src/VP-V/modules/output/dither/tests/DitherNeedGolden.generated.h for DitherNeedTests (C++ vs dither_need_ref.py).

Run:  python -I tools/eval/gen_dither_need_golden.py

Three deterministic 96x64 luma frames in 10-bit codes (a gently sloped ramp; noise from a fixed integer LCG, no numpy
random): (0) grain-free, (1) faint grain (+-1 code), (2) stronger grain (+-2 codes). Context: HdrToSdr, source peak 1000
nit, LightLevel defaults, 8-bit link (q_out 4), DitherNeed::Params defaults. Embedded: the LUT's V and Sout (1024 each), the
luma, the python block inputs per frame (N, meanY, banding, inPicture; B = 8 at 64 lines, a 12x8 grid), the per-block target
per frame, the smoothed state e over a 6-step sequence (first frame, a discontinuity, different frame intervals, repeats that
hit the deadband) and the sampled extra amplitude at 12 pixels per step (scale 0.75, offset 3.0 / 1.5, 8 px blocks).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402

import dither_need_ref as dn  # noqa: E402
import light_level_ref as llr  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, "..", "..", "src", "VP-V", "modules", "output", "dither", "tests",
                                    "DitherNeedGolden.generated.h"))
W, H = 96, 64
COLOR_BITS = 8
SCALE, OFF_X, OFF_Y = 0.75, 3.0, 1.5
SAMPLES = [(0, 0), (1, 1), (7, 3), (16, 9), (33, 20), (50, 31), (64, 40), (95, 63), (100, 70), (127, 79), (5, 75), (120, 2)]
# (frame, discontinuity, dt seconds)
STEPS = [(0, 0, 1.0 / 60), (1, 1, 1.0 / 60), (2, 0, 1.0 / 30), (1, 0, 1.0 / 60), (1, 0, 1.0 / 24), (0, 0, 1.0 / 24)]


def lcg(n, seed):
    s = seed
    out = []
    for _ in range(n):
        s = (s * 1664525 + 1013904223) & 0xFFFFFFFF
        out.append(s >> 16)
    return np.array(out, dtype=np.int64)


def frames():
    x = np.arange(W)[None, :]
    yy = np.arange(H)[:, None]
    r = lcg(W * H, 12345).reshape(H, W)
    out = []
    for base, amp in ((650, 0), (580, 1), (610, 2)):
        y = np.floor(base + x * 0.9 + yy * 0.2).astype(np.int64)
        if amp:
            y = y + (r % (2 * amp + 1) - amp)
        out.append(y)
    return out


def arr(name, a, fmt, ctype="double"):
    flat = np.asarray(a).reshape(-1)
    body = ", ".join(fmt % v for v in flat)
    return "static const %s %s[%d] = { %s };\n" % (ctype, name, flat.size, body)


def main():
    lut = llr.build_lut(llr.Context(kind="hdr_to_sdr", src_peak=1000.0))
    p = dn.Params()
    q = dn.q_out(COLOR_BITS)
    ys = frames()
    inputs, targets = [], []
    for y in ys:
        inp = dn.block_lut_inputs(dn.block_inputs_from_luma(y.astype(np.float64)), lut)
        inputs.append(inp)
        targets.append(dn.target_block(p, inp["N"], inp["V"], inp["Sout"], inp["banding"], inp["inPicture"], inp["overlay"], q))
    grid = inputs[0]["grid"]
    gw, gh, B = grid["gw"], grid["gh"], grid["B"]
    st = dn.Map()
    es, sampled, holds = [], [], 0
    for (f, disc, dt) in STEPS:
        before = None if st.e is None else st.e.copy()
        valid_before = st.valid
        st.update(p, (gh, gw), inputs[f], dt, bool(disc), True, 0, True, COLOR_BITS, "golden")
        if before is not None and valid_before and not disc:
            holds += int(np.sum(np.abs(targets[f] - before) <= p.deadband))
        es.append(st.e.copy())
        px = np.array([s[0] for s in SAMPLES]); py = np.array([s[1] for s in SAMPLES])
        sampled.append(dn.sample_extra(st.e, B, SCALE, SCALE, OFF_X, OFF_Y, px, py))
    print("grid %dx%d B=%d, deadband holds in the sequence: %d" % (gw, gh, B, holds))
    for i, t in enumerate(targets):
        print("frame %d target min %.4f max %.4f nonzero %d/%d" % (i, t.min(), t.max(), int((t > 0).sum()), t.size))
    assert holds > 0, "sequence must exercise the deadband hold"

    h = []
    h.append("// Copyright(C) 2026 VP-V contributors\n// SPDX-License-Identifier: GPL-3.0-only\n//\n")
    h.append("// GENERATED by:  python -I tools/eval/gen_dither_need_golden.py   (do not edit)\n")
    h.append("// DitherNeed golden vectors from tools/eval/dither_need_ref.py: HdrToSdr 1000 nit LUT (LightLevel defaults), 8-bit link,\n")
    h.append("// DitherNeed::Params defaults, three 96x64 luma frames. See the generator for the construction.\n#pragma once\n\n")
    h.append("namespace DitherNeedGolden\n{\n")
    h.append("\tconstexpr int kW = %d, kH = %d, kB = %d, kGw = %d, kGh = %d, kBlocks = %d, kColorBits = %d, kFrames = 3, kSteps = %d, kSamples = %d;\n"
             % (W, H, B, gw, gh, gw * gh, COLOR_BITS, len(STEPS), len(SAMPLES)))
    h.append("\tconstexpr double kScale = %r, kOffX = %r, kOffY = %r;\n" % (SCALE, OFF_X, OFF_Y))
    h.append("\tstruct Step { int frame; int discontinuity; double dt; };\n")
    h.append("\tstatic const Step kStep[kSteps] = { %s };\n" % ", ".join("{ %d, %d, %.17g }" % s for s in STEPS))
    h.append("\tstatic const int kSampleX[kSamples] = { %s };\n" % ", ".join(str(s[0]) for s in SAMPLES))
    h.append("\tstatic const int kSampleY[kSamples] = { %s };\n" % ", ".join(str(s[1]) for s in SAMPLES))
    h.append("\t" + arr("kLutV", lut["V"], "%.17g"))
    h.append("\t" + arr("kLutSout", lut["sout"], "%.17g"))
    h.append("\t" + arr("kLuma", np.concatenate([y.reshape(-1) for y in ys]), "%d", "short"))
    h.append("\t" + arr("kN", np.concatenate([i["N"].reshape(-1) for i in inputs]), "%.17g"))
    h.append("\t" + arr("kMeanY", np.concatenate([i["meanY"].reshape(-1) for i in inputs]), "%.17g"))
    h.append("\t" + arr("kBanding", np.concatenate([i["banding"].reshape(-1) for i in inputs]), "%.17g"))
    h.append("\t" + arr("kInPicture", np.concatenate([i["inPicture"].reshape(-1).astype(int) for i in inputs]), "%d", "int"))
    h.append("\t" + arr("kTarget", np.concatenate([t.reshape(-1) for t in targets]), "%.17g"))
    h.append("\t" + arr("kE", np.concatenate([e.reshape(-1) for e in es]), "%.17g"))
    h.append("\t" + arr("kSampled", np.concatenate([s.reshape(-1) for s in sampled]), "%.9ef", "float"))
    h.append("}\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(h))
    print("wrote", OUT, os.path.getsize(OUT), "bytes")


if __name__ == "__main__":
    main()
