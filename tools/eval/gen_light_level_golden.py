"""Generates two headers for the light-level LUT tests (tests/ folder of the light_level module):
  LightLevelGolden.generated.h       tonemap_ref.SplineTM golden values (below)
  LightLevelCrossCheck.generated.h   J and L (1024 codes) of light_level_ref.build_lut for the CASES list: settings
                                     as C++ config keys ("key=value;..."), kind, source/display peaks (see CASES).

For source peaks 1000 / 4000 / 10000 nit, dst 100 nit, black 0 and the VP default ToneMappingTuning constants
(tonemap_ref.VP_DEFAULTS == ToneMappingTuning::Specs() defaults), every 10-bit limited-range code 0..1023:
  pq   = SplineTM(code_to_norm(code))     the PQ output of the spline (input clipped to [in_min, in_max])
  sdr  = pq_out_to_sdr_code(pq, 100)      the SDR signal code (64 + 876 (L/100)^(1/2.4))
Deterministic: values are written with %.17g (round-trip exact), fixed order.

Run:  python -I tools/eval/gen_light_level_golden.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402
import light_level_ref as llr  # noqa: E402
import tonemap_ref as T  # noqa: E402

PEAKS = (1000, 4000, 10000)
DST_PEAK = 100.0
OUT = os.path.normpath(os.path.join(
    HERE, "..", "..", "src", "VP-V", "modules", "input", "source_analysis", "light_level", "tests",
    "LightLevelGolden.generated.h"))
OUT_CROSS = os.path.join(os.path.dirname(OUT), "LightLevelCrossCheck.generated.h")

# name, kind (C++ Context::Kind index: 0 Sdr, 1 HdrPassthrough, 2 HdrToSdr), config keys, Context kwargs for python.
# Sets: A = defaults (203 / 0, bt1886, display auto); B = target 203 / black 0.05; C = display 300 / 0.1 on top of B;
# D = sRGB transfer; E = power 2.2; src_peak / display_peak are the C++ Context sourcePeakNits / displayPeakNits.
_B = {"sdr_target_nits": "203", "sdr_black_nits": "0.05"}
_C = dict(_B, light_level_display_white_nits="300", light_level_display_black_nits="0.1")
_D = dict(_B, hdr_tone_map_target_gamma="srgb")
_E = {"sdr_target_nits": "150", "sdr_black_nits": "0.02", "hdr_tone_map_target_gamma": "2.2"}
CASES = [
    ("SdrA", 0, {}, {}),
    ("SdrB", 0, _B, {}),
    ("SdrC", 0, _C, {}),
    ("SdrD", 0, _D, {}),
    ("SdrE", 0, _E, {}),
    ("PassA", 1, {}, dict(src_peak=4000.0, display_peak=1000.0)),
    ("PassB", 1, _B, dict(src_peak=4000.0, display_peak=1000.0)),
    ("PassC", 1, _C, dict(src_peak=4000.0, display_peak=1000.0)),
    ("PassOpen", 1, _B, dict(src_peak=1000.0, display_peak=0.0)),
    ("ToSdrA1000", 2, {}, dict(src_peak=1000.0)),
    ("ToSdrA4000", 2, {}, dict(src_peak=4000.0)),
    ("ToSdrB1000", 2, _B, dict(src_peak=1000.0)),
    ("ToSdrC4000", 2, _C, dict(src_peak=4000.0)),
    ("ToSdrD1000", 2, _D, dict(src_peak=1000.0)),
]
_KEYMAP = {"sdr_target_nits": ("target_white", float), "sdr_black_nits": ("target_black", float),
           "light_level_display_white_nits": ("display_white", float),
           "light_level_display_black_nits": ("display_black", float)}
_KIND = ("sdr", "hdr_passthrough", "hdr_to_sdr")


def case_context(kind, keys, extra):
    kw = dict(kind=_KIND[kind], **extra)
    for k, v in keys.items():
        if k == "hdr_tone_map_target_gamma":
            if v in ("bt1886", "srgb"):
                kw["eotf"] = v
            else:
                kw["eotf"], kw["gamma"] = "power", float(v)
        else:
            kw[_KEYMAP[k][0]] = float(v)
    return llr.Context(**kw)


def rows(peak):
    tm = T.SplineTM(peak, DST_PEAK, 0.0, 0.0)
    codes = np.arange(1024, dtype=np.float64)
    pq = tm(T.code_to_norm(codes))
    sdr = T.pq_out_to_sdr_code(pq, DST_PEAK)
    return pq, sdr


def emit(name, values):
    lines = ["\tconstexpr double %s[1024] = {" % name]
    for i in range(0, 1024, 4):
        lines.append("\t\t" + ", ".join("%.17g" % float(v) for v in values[i:i + 4]) + ",")
    lines.append("\t};")
    return lines


def write_cross():
    out = [
        "// Copyright(C) 2026 VP-V contributors",
        "// SPDX-License-Identifier: GPL-3.0-only",
        "//",
        "// GENERATED by tools/eval/gen_light_level_golden.py from tools/eval/light_level_ref.py (build_lut). Do not edit.",
        "// Per case: config keys (key=value;...), Context kind (0 Sdr, 1 HdrPassthrough, 2 HdrToSdr), source peak,",
        "// display peak, then L (nit) and J (PQ OETF of L) for the 1024 limited-range codes. Values are %.17g.",
        "#pragma once",
        "",
        "namespace LightLevelCrossCheck",
        "{",
        "	struct Case { const char* name; const char* keys; int kind; double sourcePeak; double displayPeak;",
        "		const double* L; const double* J; };",
    ]
    names = []
    for name, kind, keys, extra in CASES:
        ctx = case_context(kind, keys, extra)
        lut = llr.build_lut(ctx)
        out += emit("kL%s" % name, lut["L"])
        out += emit("kJ%s" % name, lut["J"])
        kstr = ";".join("%s=%s" % (k, keys[k]) for k in sorted(keys))
        names.append('		{ "%s", "%s", %d, %.1f, %.1f, kL%s, kJ%s },'
                     % (name, kstr, kind, extra.get("src_peak", 0.0), extra.get("display_peak", 0.0), name, name))
    out.append("	constexpr int kCaseCount = %d;" % len(CASES))
    out.append("	constexpr Case kCases[kCaseCount] = {")
    out += names
    out.append("	};")
    out.append("}")
    with open(OUT_CROSS, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT_CROSS)


def main():
    write_cross()
    d = T.VP_DEFAULTS
    out = [
        "// Copyright(C) 2026 VP-V contributors",
        "// SPDX-License-Identifier: GPL-3.0-only",
        "//",
        "// GENERATED by tools/eval/gen_light_level_golden.py from tools/eval/tonemap_ref.py (SplineTM,",
        "// pq_out_to_sdr_code). Do not edit. Dst peak 100 nit, black 0, source min 0, VP default tone constants:",
        "// knee_adaptation %r knee_minimum %r knee_maximum %r knee_default %r slope_tuning %r slope_offset %r"
        % (d["knee_adaptation"], d["knee_minimum"], d["knee_maximum"], d["knee_default"], d["slope_tuning"], d["slope_offset"]),
        "// spline_contrast %r. Index = 10-bit limited-range code (signal (code - 64) / 876)." % d["spline_contrast"],
        "#pragma once",
        "",
        "namespace LightLevelGolden",
        "{",
        "\tconstexpr int kPeakCount = %d;" % len(PEAKS),
        "\tconstexpr double kPeaks[kPeakCount] = { %s };" % ", ".join("%.1f" % p for p in PEAKS),
        "\tconstexpr double kDstPeak = %.1f;" % DST_PEAK,
    ]
    pqs, sdrs = [], []
    for p in PEAKS:
        pq, sdr = rows(p)
        out += emit("kPq%d" % p, pq)
        out += emit("kSdr%d" % p, sdr)
        pqs.append("kPq%d" % p)
        sdrs.append("kSdr%d" % p)
    out.append("\tconstexpr const double* kPq[kPeakCount] = { %s };" % ", ".join(pqs))
    out.append("\tconstexpr const double* kSdr[kPeakCount] = { %s };" % ", ".join(sdrs))
    out.append("}")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
