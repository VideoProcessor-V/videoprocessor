"""Generates LightLevelGolden.generated.h: tonemap_ref.SplineTM golden values for the light-level LUT tests.

For source peaks 1000 / 4000 / 10000 nit, dst 100 nit, black 0 and the VP default ToneMappingTuning constants
(tonemap_ref.VP_DEFAULTS == ToneMappingTuning::Specs() defaults), every 10-bit limited-range code 0..1023:
  pq   = SplineTM(code_to_norm(code))     the PQ output of the spline (input clipped to [in_min, in_max])
  sdr  = pq_out_to_sdr_code(pq, 100)      the SDR signal code (64 + 876 (L/100)^(1/2.4))
Deterministic: values are written with %.17g (round-trip exact), fixed order.

Run:  python -I tools/eval/gen_light_level_golden.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402
import tonemap_ref as T  # noqa: E402

PEAKS = (1000, 4000, 10000)
DST_PEAK = 100.0
OUT = os.path.normpath(os.path.join(
    HERE, "..", "..", "src", "VP-V", "modules", "input", "source_analysis", "light_level", "tests",
    "LightLevelGolden.generated.h"))


def rows(peak):
    tm = T.SplineTM(peak, DST_PEAK, 0.0, 0.0)
    codes = np.arange(1024, dtype=np.float64)
    pq = tm(T.code_to_norm(codes))
    sdr = T.pq_out_to_sdr_code(pq, DST_PEAK)
    return pq, sdr


def emit(name, values):
    lines = ["\tconstexpr double %s[1024] = {" % name]
    for i in range(0, 1024, 4):
        lines.append("\t\t" + ", ".join("%.17g" % float(v) for v in values[i:i + 4]) + ",")
    lines.append("\t};")
    return lines


def main():
    d = T.VP_DEFAULTS
    out = [
        "// Copyright(C) 2026 VP-V contributors",
        "// SPDX-License-Identifier: GPL-3.0-only",
        "//",
        "// GENERATED by tools/eval/gen_light_level_golden.py from tools/eval/tonemap_ref.py (SplineTM,",
        "// pq_out_to_sdr_code). Do not edit. Dst peak 100 nit, black 0, source min 0, VP default tone constants:",
        "// knee_adaptation %r knee_minimum %r knee_maximum %r knee_default %r slope_tuning %r slope_offset %r"
        % (d["knee_adaptation"], d["knee_minimum"], d["knee_maximum"], d["knee_default"], d["slope_tuning"], d["slope_offset"]),
        "// spline_contrast %r. Index = 10-bit limited-range code (signal (code - 64) / 876)." % d["spline_contrast"],
        "#pragma once",
        "",
        "namespace LightLevelGolden",
        "{",
        "\tconstexpr int kPeakCount = %d;" % len(PEAKS),
        "\tconstexpr double kPeaks[kPeakCount] = { %s };" % ", ".join("%.1f" % p for p in PEAKS),
        "\tconstexpr double kDstPeak = %.1f;" % DST_PEAK,
    ]
    pqs, sdrs = [], []
    for p in PEAKS:
        pq, sdr = rows(p)
        out += emit("kPq%d" % p, pq)
        out += emit("kSdr%d" % p, sdr)
        pqs.append("kPq%d" % p)
        sdrs.append("kSdr%d" % p)
    out.append("\tconstexpr const double* kPq[kPeakCount] = { %s };" % ", ".join(pqs))
    out.append("\tconstexpr const double* kSdr[kPeakCount] = { %s };" % ", ".join(sdrs))
    out.append("}")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
