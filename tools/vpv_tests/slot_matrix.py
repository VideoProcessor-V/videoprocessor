#!/usr/bin/env python
"""Per-slot test matrix generator.

Reads docs/design/slots.json and writes
  docs/design/slot-test-matrix.md   (human table)
  tests/vpv/slot-matrix.json        (machine record per slot)

Usage:  python -I tools/vpv_tests/slot_matrix.py [--check]
--check regenerates in memory; exit 1 if outputs are stale, a slot lacks a
fallback entry (control slots with entry 'None' are allowed), or ids/orders
are duplicated. A null entry is allowed for control slots. Required kinds: placeholder (status placeholder/partial),
isolation, contract, chain (non-control); control slots (order >= 900)
need isolation + contract only.
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SLOTS = ROOT / "docs/design/slots.json"
OUT_MD = ROOT / "docs/design/slot-test-matrix.md"
OUT_JSON = ROOT / "tests/vpv/slot-matrix.json"
KINDS = ["placeholder", "isolation", "contract", "chain"]


def build():
    data = json.loads(SLOTS.read_text(encoding="utf-8"))
    recs, problems, ids, orders = [], [], set(), set()
    for s in data["slots"]:
        sid, order = s["id"], s["order"]
        if sid in ids: problems.append(f"duplicate id {sid}")
        if order in orders: problems.append(f"duplicate order {order}")
        ids.add(sid); orders.add(order)
        control = order >= 900
        req = []
        if not control and s["status"] in ("placeholder", "partial"): req.append("placeholder")
        req += ["isolation", "contract"] + ([] if control else ["chain"])
        tests = {k: list((s.get("tests") or {}).get(k) or []) for k in KINDS}
        missing = [k for k in req if not tests[k]]
        entry = (s.get("fallback") or {}).get("entry")
        if not entry and not control: problems.append(f"{sid}: no fallback entry")
        recs.append({"id": sid, "order": order, "status": s["status"], "hook_point": s["hook_point"],
                     "control": control, "required": req, "tests": tests,
                     "fallback_entry": entry, "missing": missing})
    return recs, problems


def render(recs):
    L = ["# Per-slot test matrix", "",
         "Generated by `tools/vpv_tests/slot_matrix.py` from `slots.json`; do not edit.", "",
         "Kinds: placeholder = byte-identity on/off + zero cost (required for placeholder/partial slots); "
         "isolation; contract (incl. fallback entry under 'Fallbacks engaged'); "
         "chain (200/250 ms total delay at 4/3/2 frames). Control slots (order >= 900) need isolation + contract only.", "",
         "| Order | Slot | Status | Hook | Placeholder | Isolation | Contract | Chain | Fallback entry |",
         "|---|---|---|---|---|---|---|---|---|"]
    def cell(r, k):
        if r["control"] and k in ("chain", "placeholder"): return "n/a (control slot)"
        if r["tests"][k]: return "<br>".join(r["tests"][k]).replace("|", "/")
        return "MISSING" if k in r["required"] else "not required"
    for r in recs:
        L.append(f"| {r['order']} | {r['id']} | {r['status']} | {r['hook_point']} | " +
                 " | ".join(cell(r, k) for k in KINDS) + f" | {(r['fallback_entry'] or '').replace('|', '/')} |")
    L += ["", "## Missing tests by kind", ""]
    for k in KINDS:
        m = [r["id"] for r in recs if k in r["missing"]]
        L.append(f"- {k}: {len(m)}" + (" (" + ", ".join(m) + ")" if m else ""))
    return "\n".join(L) + "\n"


def main():
    recs, problems = build()
    md = render(recs)
    js = json.dumps(recs, indent=1) + "\n"
    if "--check" in sys.argv:
        for p in problems: print("ERROR:", p)
        for path, text in ((OUT_MD, md), (OUT_JSON, js)):
            cur = path.read_text(encoding="utf-8") if path.exists() else None
            if cur is None or cur.replace("\r\n", "\n") != text:
                problems.append(f"stale: {path.relative_to(ROOT)}"); print("ERROR: stale", path.name)
        print("slot_matrix check:", "FAIL" if problems else "ok")
        sys.exit(1 if problems else 0)
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(md, encoding="utf-8", newline="\n")
    OUT_JSON.write_text(js, encoding="utf-8", newline="\n")
    for p in problems: print("WARNING:", p)
    print(f"wrote {len(recs)} slots")

if __name__ == "__main__":
    main()
