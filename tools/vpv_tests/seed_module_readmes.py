"""Seed each slot folder's README (src/modules/<unit>/<slot>/README.md) with a Settings and a
Tests section, generated from docs/design/slots.json, docs/design/vpv-tiers.json and
tests/vpv/slot-matrix.json. Idempotent: the generated block sits between markers and is
replaced on every run; everything else in the README is kept.

    python -I tools/vpv_tests/seed_module_readmes.py          # write
    python -I tools/vpv_tests/seed_module_readmes.py --check  # exit 1 when a README is stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
BEGIN = "<!-- vpv-settings-tests:begin (generated by tools/vpv_tests/seed_module_readmes.py) -->"
END = "<!-- vpv-settings-tests:end -->"
GUIDE = "docs/settings/VP-settings-reference.md"
GUIDE_SECTION = {"input": "2-input", "motion": "3-motion", "repair": "4-repair", "scaling": "5-scaling",
                 "colour": "6-colour", "drive": "7-dynamic-drive", "output": "8-output"}


def block(slot, unit, matrix):
    lines = [BEGIN, "", "## Settings", ""]
    keys = slot.get("settings_keys", [])
    planned = slot.get("planned_keys", [])
    lines.append("- Keys: " + (", ".join(f"`{k}`" for k in keys) if keys else "none yet") + ".")
    if planned:
        lines.append("- Planned keys (not yet implemented): " + ", ".join(f"`{k}`" for k in planned) + ".")
    lines.append(f"- Tiers: {slot.get('tiers') or 'n/a'}.")
    if unit:
        tier_keys = sorted({k for p in unit["presets"].values() for k in p["set"]})
        toggles = [t["key"] for t in unit.get("toggles", []) if t["slot"] == slot["id"]]
        if unit["tiers"]:
            lines.append(f"- VP-V page, {unit['name']} tab: tiers {' / '.join(unit['tiers'])}; tier keys "
                         + ", ".join(f"`{k}`" for k in tier_keys) + ".")
        else:
            lines.append(f"- VP-V page, {unit['name']} tab: not tiered ({unit.get('untiered_reason', '')}).")
        if toggles:
            lines.append("- Listed under the tier: " + ", ".join(f"`{k}`" for k in toggles) + ".")
        anchor = GUIDE_SECTION.get(unit["id"])
        if anchor:
            lines.append(f"- Plain-language guide: [{GUIDE}#{anchor}](../../../../{GUIDE}#{anchor}).")
    fb = (slot.get("fallback") or {}).get("entry")
    lines.append(f"- Fallback entry (\"Fallbacks engaged\"): {('`' + fb + '`') if fb else 'none (control slot)'}.")
    lines += ["", "## Tests", ""]
    rec = matrix.get(slot["id"], {})
    tests = slot.get("tests") or {}
    for kind, label in (("placeholder", "Placeholder (byte-identity on/off, zero cost)"),
                        ("isolation", "Isolation (fixed inputs, expected outputs, cost)"),
                        ("contract", "Contract (formats, geometry, fallback entry)"),
                        ("chain", "Chain (total delay at the 4/3/2-frame budgets)")):
        names = tests.get(kind) or []
        if isinstance(names, str):
            names = [names]
        required = kind in rec.get("required", [])
        if names:
            text = "; ".join(names)
        else:
            text = "MISSING" if required else "n/a"
        lines.append(f"- {label}: {text}.")
    lines.append("- Combinations: pairwise / high-risk / random lines in `tests/vpv/` that set this slot's unit "
                 "(`tools/run_combinations.ps1`); matrix: `docs/design/slot-test-matrix.md`.")
    lines += ["", END]
    return "\n".join(lines)


def main():
    slots = json.loads((ROOT / "docs/design/slots.json").read_text(encoding="utf-8"))
    tiers = json.loads((ROOT / "docs/design/vpv-tiers.json").read_text(encoding="utf-8"))
    matrix_path = ROOT / "tests/vpv/slot-matrix.json"
    raw = json.loads(matrix_path.read_text(encoding="utf-8")) if matrix_path.exists() else []
    records = raw.get("slots", raw) if isinstance(raw, dict) else raw
    matrix = {r["id"]: r for r in records}
    unit_of = {sid: u for u in tiers["units"] for sid in u["slots"]}
    stale = []
    for s in slots["slots"]:
        unit_dir, slot_dir = s["id"].split(".", 1)
        # src/VP-V/modules once the skeleton moves the module tree there; src/modules before.
        base = ROOT / "src" / "VP-V" / "modules"
        if not base.exists():
            base = ROOT / "src" / "modules"
        readme = base / unit_dir / slot_dir / "README.md"
        if not readme.parent.exists():
            print("no module folder:", readme.parent.relative_to(ROOT))
            continue
        text = readme.read_text(encoding="utf-8") if readme.exists() else f"# {s['name']} ({s['id']})\n"
        new_block = block(s, unit_of.get(s["id"]), matrix)
        if BEGIN in text and END in text:
            head, rest = text.split(BEGIN, 1)
            tail = rest.split(END, 1)[1]
            updated = head + new_block + tail
        else:
            updated = text.rstrip("\n") + "\n\n" + new_block + "\n"
        if updated != text:
            stale.append(str(readme.relative_to(ROOT)))
            if "--check" not in sys.argv:
                readme.write_text(updated, encoding="utf-8", newline="\n")
    if "--check" in sys.argv:
        for p in stale:
            print("STALE:", p)
        return 1 if stale else 0
    print(f"updated {len(stale)} README(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
