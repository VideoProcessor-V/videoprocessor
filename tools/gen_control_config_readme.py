"""Generates the per-setting table of src/VP-V/modules/control/config/README.md (M2 P3-8).

    python -I tools/gen_control_config_readme.py            # rewrites the generated part of the README
    python -I tools/gen_control_config_readme.py --check    # exit 1 when the README is out of date

Sources (no hand-kept key list):
- VpvSchemaKeys.h (renderer profile keys: group, type and range from the validator expression),
  VpvStartupSchema.h (startup keys appended to the host rule lists), the [vpv] key list;
- docs/settings/coverage-audit.md section A (generated by tools/settings_coverage_audit.py):
  section, Config control, default, flags;
- docs/design/vpv-tiers.json: the VP-V page sub-page (pipeline unit), tier presets (`set`) and toggles;
- VpvRendererSettings.cpp ApplyOriginal ("// key=" lines): the Original-pathway value;
- the module MANIFEST.json files: the "Fallbacks engaged" entry of the slot behind a key.
The table says nothing about any particular display: tiers are budget-driven.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CFG = ROOT / "src" / "VP-V" / "modules" / "control" / "config"
README = CFG / "README.md"
BEGIN = "<!-- BEGIN GENERATED SETTINGS (tools/gen_control_config_readme.py) -->"
END = "<!-- END GENERATED SETTINGS -->"
GROUP_FN = {"Input": "input", "Motion": "motion", "Scaling": "scaling", "Viewport": "viewport", "Queue": "queue", "Base": "base"}
GROUP_SECTION = {"input": "[vprenderer.*] input group", "motion": "[vprenderer.*] motion group",
                 "scaling": "[vprenderer.*] scaling group", "viewport": "[vprenderer.*] viewport group",
                 "queue": "[queue] / [queue.*] (and the queue profile group)", "base": "[vpv] / [vprenderer]"}
LIST_SECTION = {"general": "[general] / [command_line]", "queue": "[queue] / [queue.*]", "shortcuts": "[shortcuts]",
                "decklink": "[decklink]", "logging": "[logging]"}
CONSTS = {"FileAvOffsetMinMs": -2000, "FileAvOffsetMaxMs": 2000, "FileLedHoldoverMinMs": 0, "FileLedHoldoverMaxMs": 30000}


def read(p):
    return p.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")


def describe(expr):
    """Type and range of a validator expression (the text inside V(...))."""
    parts = []
    for m in re.finditer(r"IsChoice\(value,\s*\{([^}]*)\}\)", expr):
        parts.append("choice: " + ", ".join(re.findall(r'"([^"]*)"', m.group(1))))
    for m in re.finditer(r"IsNumberInRange\(\w+,\s*([-\w.]+),\s*([-\w.]+)\)", expr):
        parts.append("number %s..%s" % (m.group(1), m.group(2)))
    for m in re.finditer(r"ParseInteger\(\w+,\s*([-\w.]+),\s*([-\w.]+),", expr):
        parts.append("integer %s..%s" % (m.group(1), m.group(2)))
    if "IsBoolean(" in expr:
        parts.append("boolean")
    if "IsAspectInRange(" in expr:
        parts.append("aspect")
    if "find_first_not_of" in expr and not parts:
        parts.append("slot list text")
    if "lines(value" in expr:
        parts.append("native, auto, a height 144..8640 or WIDTHxHEIGHT (width up to 17280)")
    if "find('\"')" in expr:
        parts.append("a folder path without a double quote (empty = off)")
    return " or ".join(parts) if parts else "custom rule"


def profile_keys():
    text = read(CFG / "VpvSchemaKeys.h")
    rows = {}
    for m in re.finditer(r"inline Verdict (Input|Motion|Scaling|Viewport|Queue|Base)\(", text):
        end = text.find("return Verdict::NotMine;", m.end())
        body = text[m.end():end]
        group = GROUP_FN[m.group(1)]
        # one statement per `if (key ...` (the condition may name several keys)
        starts = [s.start() for s in re.finditer(r"if\s*\(\(?\s*key\s*==|if\(key==", body)]
        starts.append(len(body))
        for a, b in zip(starts, starts[1:]):
            st = body[a:b]
            cut = st.find("V(")
            if cut < 0:
                cut = len(st)
            keys = re.findall(r'\bkey\s*==\s*"([^"]+)"', st[:cut])
            for k in keys:
                rows[k] = (group, describe(st[cut:]))
    return rows


def startup_keys():
    text = read(CFG / "VpvStartupSchema.h")
    rows = {}
    for blk in re.finditer(r'name == "(\w+)"\)\s*\{(.*?)\n\t\t\t\}', text, re.S):
        lst, body = blk.group(1), blk.group(2)
        for m in re.finditer(r'ConfigSchema::(\w+)\("([^"]+)"([^)]*)\)', body):
            kind, key, rest = m.groups()
            if kind == "Boolean":
                t = "boolean"
            elif kind == "Integer":
                nums = [str(CONSTS.get(x.strip(), x.strip())) for x in rest.strip(", ").split(",")]
                t = "integer %s..%s" % tuple(nums[:2])
            elif kind == "Choice":
                t = "choice: " + ", ".join(re.findall(r'"([^"]*)"', rest))
            else:
                t = kind.lower()
            rows[key] = (LIST_SECTION.get(lst, lst), t)
    return rows


def vpv_keys():
    text = read(CFG / "VpvSchemaKeys.h")
    m = re.search(r"vpvKeys\[\] = \{(.*?)\};", text, re.S)
    return re.findall(r'"([^"]+)"', m.group(1)) + ["retirement_a", "retirement_b", "retirement_c", "retirement_d"]


def audit_rows():
    rows = {}
    text = read(ROOT / "docs" / "settings" / "coverage-audit.md")
    unit = ""
    for line in text.split("\n"):
        h = re.match(r"### (.+?) \(\d+\)", line)
        if h:
            unit = h.group(1)
        m = re.match(r"\| `([^`]+)` \| ([^|]*)\| ([^|]*)\| ([^|]*)\| ([^|]*)\| ([^|]*)\| ([^|]*)\| ([^|]*)\|", line)
        if m and unit:
            rows.setdefault(m.group(1), []).append(dict(
                unit=unit, section=m.group(2).strip(), upstream=m.group(3).strip(), vpv=m.group(4).strip(),
                tier=m.group(5).strip(), default=m.group(6).strip(), flags=m.group(8).strip()))
    return rows


def tiers():
    d = json.loads(read(ROOT / "docs" / "design" / "vpv-tiers.json"))
    toggle, taste, sets = {}, {}, {}
    for u in d["units"]:
        for t in u.get("toggles", []):
            toggle[t["key"]] = (u["name"], t.get("slot", ""))
        for k in u.get("taste", []):
            taste[k] = u["name"]
        for tier, p in u.get("presets", {}).items():
            for k, v in p.get("set", {}).items():
                sets.setdefault(k, []).append((u["name"], tier, v))
    return toggle, taste, sets


def original():
    text = read(CFG / "VpvRendererSettings.cpp")
    out = {}
    for m in re.finditer(r"=\s*([^;]*);[^/\n]*//\s*key=(\w+)", text):
        out[m.group(2)] = m.group(1).strip().strip('"')
    return out


def fallback_entries():
    out = {}
    for mf in (ROOT / "src" / "VP-V" / "modules").glob("*/*/MANIFEST.json"):
        try:
            d = json.loads(read(mf))
        except Exception:
            continue
        if d.get("slot") and d.get("fallback_entry"):
            out[d["slot"]] = d["fallback_entry"]
    return out


def cell(s):
    return (s or "-").replace("|", "/").replace("\n", " ")


def build():
    prof, start, vpv = profile_keys(), startup_keys(), vpv_keys()
    audit = audit_rows()
    toggle, taste, sets = tiers()
    orig = original()
    fb = fallback_entries()
    entries = []
    for k, (g, t) in prof.items():
        entries.append((k, GROUP_SECTION[g], t, g))
    for k, (s, t) in start.items():
        entries.append((k, s, t, "startup"))
    seen = {e[0] for e in entries}
    for k in vpv:
        if k not in seen:
            entries.append((k, "[vpv]", "see ValidateBaseSetting", "base"))
    entries.sort(key=lambda e: (e[3], e[0]))
    lines = ["| Key | Section | Type / range | Default | Config placement | Original (Bill) | Fallback / status | Tier differences |",
             "|---|---|---|---|---|---|---|---|"]
    for k, sec, typ, grp in entries:
        a0 = audit.get(k, [{}])[0]
        place = []
        if a0.get("upstream") and a0["upstream"] != "-":
            place.append(a0["upstream"])
        if k in toggle:
            place.append("VP-V page > %s (toggle)" % toggle[k][0])
        elif k in taste:
            place.append("VP-V page > %s (taste)" % taste[k])
        elif a0.get("vpv") and a0["vpv"] != "-":
            place.append(a0["vpv"])
        if not place:
            place.append("Config page of its section" + (" (audit unit: %s)" % a0["unit"] if a0.get("unit") else ""))
        original_cell = ("Original sets %s" % (orig[k] or "(empty)")) if k in orig else "unchanged by Original"
        status = []
        slot = toggle.get(k, ("", ""))[1]
        if slot in fb:
            status.append(fb[slot])
        if a0.get("flags"):
            status.append(a0["flags"])
        tier = "; ".join("%s %s=%s" % (u, t, v) for u, t, v in sets.get(k, []))
        lines.append("| `%s` | %s | %s | %s | %s | %s | %s | %s |" % (
            k, cell(sec), cell(typ), cell(a0.get("default", "")), cell("; ".join(place)),
            cell(original_cell), cell("; ".join(status)), cell(tier)))
    head = ("Generated by `tools/gen_control_config_readme.py` from the schema headers, the settings coverage audit, "
            "`docs/design/vpv-tiers.json`, `ApplyOriginal` and the module manifests; do not edit by hand. "
            "%d settings. Tiers are budget-driven (the tier presets list the values they set); no setting is tied to "
            "one display or GPU model.\n\n" % len(entries))
    return head + "\n".join(lines) + "\n"


def main():
    body = build()
    text = read(README)
    block = BEGIN + "\n\n" + body + "\n" + END
    if BEGIN in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        new = text[:a] + block + text[b:]
    else:
        new = text.replace("## Contract", "## Settings table (moved settings)\n\n" + block + "\n\n## Contract", 1)
    if "--check" in sys.argv:
        sys.exit(0 if new == text else 1)
    README.write_text(new, encoding="utf-8", newline="\n")
    print("rows:", body.count("\n| `"))


if __name__ == "__main__":
    main()
