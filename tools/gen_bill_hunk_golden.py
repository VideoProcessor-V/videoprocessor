"""Generates src/VP-V/tests/golden/bill-hunks.golden.txt, the Bill baseline of BillIdenticalSchemaTests.

Owner decision 2026-11-07: where P3 touches Bill's files, Bill's own lists and texts stay Bill's. The golden
holds, from the Bill baseline commit (a591ad3b), the whitespace-and-comment-free text of
  general/queue/decklink/logging  the rule lists of MainConfigSchema::Validate (Bill: inline vectors),
  baseKeys                         the legacy [display] key set of RendererProfileConfig.h,
  exprvars1/exprvars2              the two `when=` variable lists,
  describe_delta                   the whole body of DescribeProfileSettingsDelta (the 'profile changed' text).
Format: one 'name<TAB>text' line per entry. The test finds the same blocks in the CURRENT sources and compares.

Usage (repository root):  python -I tools/gen_bill_hunk_golden.py [--check]
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "a591ad3b"
OUT = ROOT / "src" / "VP-V" / "tests" / "golden" / "bill-hunks.golden.txt"


def bill(path):
    return subprocess.check_output(["git", "show", BASE + ":" + path], cwd=ROOT).decode("utf-8").replace("\r\n", "\n")


def squash(text):
    text = re.sub(r"//[^\n]*", "", text)
    return re.sub(r"\s+", "", text)


def block_after(text, start):
    """Text inside the first {...} at/after `start`."""
    i = text.index("{", start)
    depth, j = 1, i + 1
    while depth:
        depth += {"{": 1, "}": -1}.get(text[j], 0)
        j += 1
    return text[i + 1:j - 1]


def function_after(text, marker):
    i = text.index(marker)
    j = text.index("\n\t}\n", i)
    return text[i:j + 4]


def main():
    main_h = bill("src/VideoProcessor-Lib/MainConfigSchema.h")
    prof_h = bill("src/VideoProcessor-Lib/RendererProfileConfig.h")
    lvr = bill("src/VideoProcessor-Lib/vprenderer/LibplaceboVideoRenderer.cpp")
    entries = {}
    for name, marker in (("general", "commandLineRules = {"), ("queue", "queueRules = {"),
                         ("decklink", "deckLinkRules = {"), ("logging", "loggingRules = {")):
        entries[name] = squash(block_after(main_h, main_h.index(marker)))
    entries["baseKeys"] = squash(block_after(prof_h, prof_h.index("const std::set<std::string> baseKeys = {")))
    entries["exprvars1"] = squash(block_after(prof_h, prof_h.index("const std::set<std::string> expressionVariables = {")))
    m = re.search(r"ValidateExpressionVariables\(profile\.whenExpression,\s*\{", prof_h)
    entries["exprvars2"] = squash(block_after(prof_h, m.start()))
    entries["describe_delta"] = squash(function_after(lvr, "static std::string DescribeProfileSettingsDelta("))
    text = "# Bill baseline " + BASE + " (generated by tools/gen_bill_hunk_golden.py)\n" + \
        "".join("%s\t%s\n" % (k, v) for k, v in entries.items())
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8").replace("\r\n", "\n") == text else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT, {k: len(v) for k, v in entries.items()})
    return 0


if __name__ == "__main__":
    sys.exit(main())
