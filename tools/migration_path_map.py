#!/usr/bin/env python3
"""Old path -> new path map for code migrated into src/VP-V/modules (ADR-0017).

The map (docs/design/migration-path-map.md) is generated from git renames into src/VP-V/modules
plus the modules' forwarding headers, so references in dated historical records (agent reports,
audits, prompts) stay resolvable after a move. Living documents, scripts and source comments must
use the new paths; this tool finds the ones that still name an old path.

  python tools/migration_path_map.py            # check: map current + no living references; exit 1 otherwise
  python tools/migration_path_map.py --write    # regenerate the map
  python tools/migration_path_map.py --fix      # rewrite old-path references in living files

tools/check_module_manifests.py runs the check too. Stdlib + git only.
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP = os.path.join(ROOT, "docs", "design", "migration-path-map.md")
MODULES_REL = "src/VP-V/modules/"
LIB_REL = "src/VideoProcessor-Lib/"

# Dated historical records keep the paths they were written with; the map resolves them.
HISTORICAL_PREFIXES = ("docs/agent-reports/", "docs/audit/")
EXCLUDED_FILES = {
    "docs/design/migration-path-map.md",        # the map itself
    "docs/design/migration-early-inventory.md",  # describes the moves, names the old paths on purpose
    "docs/design/migration-m2-plan.md",          # names the forwarding headers (old paths) on purpose
}
LIVING_EXT = {".md", ".txt", ".py", ".ps1", ".psm1", ".cmd", ".bat", ".sh", ".yml", ".yaml", ".json",
              ".html", ".cpp", ".h", ".hpp", ".inl", ".c", ".glsl", ".hlsl"}


def is_historical(rel):
    return rel.startswith(HISTORICAL_PREFIXES) or "prompt" in os.path.basename(rel).lower()


def git(*args):
    return subprocess.run(["git", "-C", ROOT] + list(args), capture_output=True, text=True,
                          encoding="utf-8", errors="replace", check=True).stdout


def collect():
    """[(old, new, commit)] for legacy files now under src/VP-V/modules."""
    entries = {}
    commit = None
    # Staged moves (git mv, not yet committed) first, so a migration is checked before its commit.
    staged = ["@staged"] + git("diff", "--cached", "-M", "--diff-filter=R", "--name-status").splitlines()
    history = git("log", "-M", "--diff-filter=R", "--format=@%h", "--name-status", "HEAD").splitlines()
    for line in staged + history:
        if line.startswith("@"):
            commit = line[1:]
            continue
        parts = line.split("\t")
        if len(parts) == 3 and parts[0].startswith("R"):
            old, new = parts[1], parts[2]
            if new.startswith(MODULES_REL) and old.startswith("src/VideoProcessor-") and old not in entries:
                if os.path.exists(os.path.join(ROOT, new)):
                    entries[old] = (new, commit)   # newest first: the first record wins
    # A header that left a forwarding header behind shows as an add, not a rename.
    for dirpath, _, files in os.walk(os.path.join(ROOT, *MODULES_REL.split("/"))):
        if "MANIFEST.json" not in files:
            continue
        with open(os.path.join(dirpath, "MANIFEST.json"), encoding="utf-8") as f:
            m = json.load(f)
        for fwd in m.get("forwarding_headers", []):
            name = os.path.basename(fwd)
            for dp, _, fs in os.walk(dirpath):
                if name in fs and "tests" not in os.path.relpath(dp, dirpath).split(os.sep):
                    new = os.path.relpath(os.path.join(dp, name), ROOT).replace(os.sep, "/")
                    added = git("log", "--diff-filter=A", "--format=%h", "-1", "--", new).strip()
                    entries[fwd] = (new, added or "?")
    return sorted(((o, n, c) for o, (n, c) in entries.items()), key=lambda e: e[1])


def render(entries):
    lines = [
        "# Migration path map",
        "",
        "Generated by `python tools/migration_path_map.py --write` from git renames into",
        "`src/VP-V/modules` and the modules' `forwarding_headers`. Do not edit by hand.",
        "",
        "Dated historical records (`docs/agent-reports/`, `docs/audit/`, prompts) keep the paths they were",
        "written with; use this table to resolve them. Short forms in those records (`led/X.cpp`,",
        "`calibration/X.h`, `vprenderer/X.h`) are relative to `src/VideoProcessor-Lib/`. Living documents",
        "use the new paths (the drift check enforces it). A forwarding header (\"fwd\") still exists at",
        "the old path until M2 so files on active branches keep building.",
        "",
        "| Old path | New path | Commit | Note |",
        "|---|---|---|---|",
    ]
    for old, new, commit in entries:
        note = "fwd" if os.path.exists(os.path.join(ROOT, old)) else ""
        lines.append(f"| `{old}` | `{new}` | {commit} | {note} |")
    return "\n".join(lines) + "\n"


def read_map():
    if not os.path.exists(MAP):
        return None
    rows = []
    with open(MAP, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|", line)
            if m and m.group(1) != "Old path":
                rows.append((m.group(1), m.group(2)))
    return rows


def patterns(rows):
    """(regex, replacement-builder) per moved stem: full Lib paths and the short dir/X forms."""
    out = []
    by_stem = {}
    for old, new in rows:
        if not old.startswith(LIB_REL):
            continue
        stem_old = os.path.splitext(old[len(LIB_REL):])[0]          # e.g. "led/<Name>"
        by_stem.setdefault(stem_old, os.path.splitext(new)[0])
    # Longest first so StateReportSettings wins over StateReport.
    for stem_old in sorted(by_stem, key=len, reverse=True):
        new_stem = by_stem[stem_old]
        d, name = os.path.split(stem_old)
        sep = r"[/\\]"
        dir_part = (re.escape(d) + sep) if d else ""
        full = r"(?P<pre>(?:src" + sep + r")?VideoProcessor-Lib" + sep + r")"
        prefix = full + ("?" if d else "")
        rx = re.compile(r"(?<![\w-])" + prefix + dir_part + re.escape(name) +
                        r"(?P<suf>\.(?:cpp|hpp|h|inl)|\.\*|\.\{[^}\s]*\})?(?![\w])")
        out.append((rx, new_stem))
    return out


def living_files():
    for rel in git("ls-files").splitlines():
        if rel in EXCLUDED_FILES or is_historical(rel) or rel.startswith("3rdparty/"):
            continue
        if os.path.splitext(rel)[1].lower() not in LIVING_EXT:
            continue
        if rel.startswith(MODULES_REL) and rel.endswith("MANIFEST.json"):
            continue
        yield rel


def scan(rows, fix=False, skip=()):
    """[(file, line no, text)] of living references to an old path; rewrites them with fix=True."""
    pats = patterns(rows)
    # A module README naming a forwarding header by its full path (its forwarder list) refers to
    # the existing forwarder file, not to moved code.
    forwarders = {o for o, _ in rows if os.path.exists(os.path.join(ROOT, o))}
    hits = []
    for rel in living_files():
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            continue
        with open(path, "rb") as f:
            raw = f.read()
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            continue
        if "VideoProcessor-Lib" not in text and not any(k in text for k in ("led/", "led\\", "calibration/", "calibration\\", "vprenderer/", "vprenderer\\")):
            continue
        new_lines = []
        changed = False
        in_module_doc = rel.startswith(MODULES_REL) and rel.endswith("README.md")
        for no, line in enumerate(text.splitlines(keepends=True), 1):
            if re.match(r"\s*#\s*include\b", line):
                new_lines.append(line)   # includes are the build's business (forwarders cover old ones)
                continue
            orig = line
            for rx, new_stem in pats:
                def repl(m):
                    start = m.start()
                    token_start = max(line.rfind(c, 0, start) for c in " \t`'\"([<|,") + 1
                    if "VP-V" in line[token_start:start]:
                        return m.group(0)   # already a new path (calibration_lut/calibration/...)
                    pre = m.group("pre") or ""
                    if in_module_doc and m.group(0).replace("\\", "/") in forwarders:
                        return m.group(0)
                    base = ("src/" if pre.startswith("src") else "") + new_stem[len("src/"):]
                    if "\\" in m.group(0):
                        base = base.replace("/", "\\")
                    return base + (m.group("suf") or "")
                line = rx.sub(repl, line)
            if line != orig:
                hits.append((rel, no, orig.strip()))
                changed = True
            new_lines.append(line)
        if fix and changed and rel not in skip:
            with open(path, "wb") as f:
                f.write("".join(new_lines).encode("utf-8"))
    return hits


def problems():
    errs = []
    try:
        entries = collect()
    except (OSError, subprocess.CalledProcessError) as e:
        return [f"migration path map: git unavailable ({e}); map not verified"]
    rows = read_map()
    want = [(o, n) for o, n, _ in entries]
    if rows is None:
        if want:
            errs.append("docs/design/migration-path-map.md missing (run tools/migration_path_map.py --write)")
        return errs
    if sorted(rows) != sorted(want):
        errs.append("docs/design/migration-path-map.md is out of date (run tools/migration_path_map.py --write)")
    for rel, no, text in scan(want):
        errs.append(f"old path in living file {rel}:{no}: {text[:120]}")
    return errs


def main():
    if "--write" in sys.argv[1:]:
        entries = collect()
        with open(MAP, "w", encoding="utf-8", newline="\n") as f:
            f.write(render(entries))
        print(f"wrote {os.path.relpath(MAP, ROOT)} ({len(entries)} files)")
        return 0
    if "--fix" in sys.argv[1:]:
        skip = set()
        if "--skip" in sys.argv:
            with open(sys.argv[sys.argv.index("--skip") + 1], encoding="utf-8") as f:
                skip = {l.strip() for l in f if l.strip()}
        rows = [(o, n) for o, n, _ in collect()]
        hits = scan(rows, fix=True, skip=skip)
        for rel, no, text in hits:
            print(("SKIPPED " if rel in skip else "fixed ") + f"{rel}:{no}: {text[:140]}")
        return 0
    errs = problems()
    for e in errs:
        print("DRIFT:", e)
    print(f"migration path map: {len(errs)} problems")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
