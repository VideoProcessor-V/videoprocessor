		TEST_METHOD(SampleLoadsAndReleasesDeterministically)
		{
			ResyncInject inj(ResyncSched::Env("1"));
			std::string err;
			Assert::IsTrue(inj.LoadSchedule(ResyncSched::Sample(), err), ResyncSched::W(err).c_str());
			Assert::AreEqual<uint64_t>(42, inj.ScheduleSeed());
			Assert::AreEqual<size_t>(10, inj.ScheduleRemaining());

			Assert::AreEqual<size_t>(0, inj.Release(4.9, 3999), L"nothing due yet");
			Assert::AreEqual<size_t>(3, inj.Release(40.0, 3999), L"inplace, overflow, rpu_loss");
			auto got = ResyncSched::Drain(inj);
			Assert::AreEqual<size_t>(3, got.size());
			Assert::IsTrue(got[0].kind == ResyncInject::Kind::InPlace);
			Assert::AreEqual<uint32_t>(3, got[0].line);
			Assert::IsTrue(got[1].kind == ResyncInject::Kind::Overflow);
			Assert::AreEqual<int64_t>(191, got[1].value);
			Assert::IsTrue(got[2].kind == ResyncInject::Kind::RpuLoss);
			Assert::AreEqual<int64_t>(128, got[2].value);
			Assert::AreEqual<uint32_t>(5, got[2].line);
			Assert::AreEqual<uint32_t>(128, inj.RpuLossFramesToDrop(), L"release applies the adapter side");
			Assert::AreEqual<uint32_t>(191, inj.TakeOverflowFrames());

			Assert::AreEqual<size_t>(0, inj.Release(40.0, 3999), L"idempotent");
			Assert::AreEqual<size_t>(1, inj.Release(40.0, 4000), L"seq entry becomes due");
			got = ResyncSched::Drain(inj);
			Assert::IsTrue(got.size() == 1 && got[0].kind == ResyncInject::Kind::Gap && got[0].value == 3 && got[0].line == 7);
			Assert::AreEqual<uint32_t>(3, inj.TakeGapFramesToDrop());

			// Everything else at once: file order across both clocks.
			Assert::AreEqual<size_t>(6, inj.Release(1000.0, 9000));
			got = ResyncSched::Drain(inj);
			const ResyncInject::Kind order[] = { ResyncInject::Kind::RpuReturn, ResyncInject::Kind::SignalLoss,
				ResyncInject::Kind::SignalReturn, ResyncInject::Kind::TunnelHandoff, ResyncInject::Kind::DvSwitch,
				ResyncInject::Kind::Minor };
			const uint32_t lines[] = { 6, 8, 9, 10, 11, 12 };
			Assert::AreEqual<size_t>(6, got.size());
			for (size_t i = 0; i < 6; ++i)
			{
				Assert::IsTrue(got[i].kind == order[i]);
				Assert::AreEqual<uint32_t>(lines[i], got[i].line);
				Assert::IsTrue(got[i].injected);
			}
			Assert::AreEqual<int64_t>(1, got[4].value, L"dv_switch lldv");
			Assert::AreEqual<size_t>(0, inj.ScheduleRemaining());
			Assert::AreEqual<uint64_t>(0, inj.ScheduleBlocked());
		}

