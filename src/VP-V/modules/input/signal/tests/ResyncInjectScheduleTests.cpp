		TEST_METHOD(NewKindsParseAndQueue)
		{
			ResyncInject inj(ResyncSched::Env("1"));
			const char* const ok[] = { "dv_switch tunnel", "dv_switch lldv", "dv_switch hdr10", "dv_switch sdr", "rpu_loss 1",
				"rpu_loss 100000", "rpu_return", "tunnel_handoff", "signal_loss 600000", "signal_return", "minor", "minor 7",
				"full", "overflow 1000" };
			ResyncInject::Kind kinds[] = { ResyncInject::Kind::DvSwitch, ResyncInject::Kind::DvSwitch, ResyncInject::Kind::DvSwitch,
				ResyncInject::Kind::DvSwitch, ResyncInject::Kind::RpuLoss, ResyncInject::Kind::RpuLoss, ResyncInject::Kind::RpuReturn,
				ResyncInject::Kind::TunnelHandoff, ResyncInject::Kind::SignalLoss, ResyncInject::Kind::SignalReturn,
				ResyncInject::Kind::Minor, ResyncInject::Kind::Minor, ResyncInject::Kind::Full, ResyncInject::Kind::Overflow };
			const int64_t values[] = { 0, 1, 2, 3, 1, 100000, 0, 0, 600000, 0, 0, 7, 0, 1000 };
			for (size_t i = 0; i < sizeof(ok) / sizeof(ok[0]); ++i)
			{
				Assert::IsTrue(inj.Invoke("resync.inject", ok[i]).rfind("ok: queued ", 0) == 0, L"accepted");
				ResyncInject::Request r;
				Assert::IsTrue(inj.Poll(r));
				Assert::IsTrue(r.kind == kinds[i]);
				Assert::AreEqual<int64_t>(values[i], r.value);
				Assert::IsFalse(r.injected, L"direct Invoke is not a scheduled injection");
				Assert::AreEqual<uint32_t>(0, r.line);
			}
		}

		TEST_METHOD(NewKindsRejectBadArguments)
		{
			ResyncInject inj(ResyncSched::Env("1"));
			const char* const bad[] = { "dv_switch", "dv_switch bogus", "dv_switch tunnel lldv", "rpu_loss", "rpu_loss 0",
				"rpu_loss 100001", "rpu_return 3", "tunnel_handoff 1", "signal_loss", "signal_loss 600001", "signal_loss -5",
				"signal_return 1", "minor 0", "minor 1001", "minor x", "full 2", "overflow", "overflow 0", "overflow 1001" };
			for (const char* a : bad)
				Assert::IsTrue(inj.Invoke("resync.inject", a).rfind("error: ", 0) == 0, L"rejected");
			ResyncInject::Request r;
			Assert::IsFalse(inj.Poll(r), L"nothing queued by a rejected request");
		}

		TEST_METHOD(AdapterAccessorsTakeOnce)
		{
			ResyncInject inj(ResyncSched::Env("1"));
			Assert::IsTrue(inj.TakeDvSwitch() == ResyncInject::DvTarget::None);
			Assert::AreEqual<uint32_t>(0, inj.RpuLossFramesToDrop());
			Assert::IsFalse(inj.RpuReturnPending());
			Assert::IsFalse(inj.TakeTunnelHandoff());
			Assert::AreEqual<uint32_t>(0, inj.TakeSignalLossMs());
			Assert::IsFalse(inj.SignalReturnPending());
			Assert::AreEqual<uint32_t>(0, inj.TakeOverflowFrames());

			inj.Invoke("resync.inject", "dv_switch hdr10");
			Assert::IsTrue(inj.TakeDvSwitch() == ResyncInject::DvTarget::Hdr10);
			Assert::IsTrue(inj.TakeDvSwitch() == ResyncInject::DvTarget::None, L"taken once");
			inj.Invoke("resync.inject", "rpu_loss 40");
			inj.Invoke("resync.inject", "rpu_loss 2");
			Assert::AreEqual<uint32_t>(42, inj.RpuLossFramesToDrop(), L"accumulates");
			Assert::AreEqual<uint32_t>(0, inj.RpuLossFramesToDrop());
			inj.Invoke("resync.inject", "rpu_loss 40");
			inj.Invoke("resync.inject", "rpu_return");
			Assert::AreEqual<uint32_t>(0, inj.RpuLossFramesToDrop(), L"the return cancels the rest of the loss");
			Assert::IsTrue(inj.RpuReturnPending());
			Assert::IsFalse(inj.RpuReturnPending());
			inj.Invoke("resync.inject", "tunnel_handoff");
			Assert::IsTrue(inj.TakeTunnelHandoff());
			Assert::IsFalse(inj.TakeTunnelHandoff());
			inj.Invoke("resync.inject", "signal_loss 1500");
			Assert::AreEqual<uint32_t>(1500, inj.TakeSignalLossMs());
			Assert::AreEqual<uint32_t>(0, inj.TakeSignalLossMs());
			inj.Invoke("resync.inject", "signal_loss 1500");
			inj.Invoke("resync.inject", "signal_return");
			Assert::AreEqual<uint32_t>(0, inj.TakeSignalLossMs());
			Assert::IsTrue(inj.SignalReturnPending());
			inj.Invoke("resync.inject", "overflow 30");
			inj.Invoke("resync.inject", "overflow 20");
			Assert::AreEqual<uint32_t>(50, inj.TakeOverflowFrames());
			ResyncInject::Request r;
			size_t polled = 0;
			while (inj.Poll(r))
				++polled;
			Assert::AreEqual<size_t>(11, polled, L"every valid request also reaches the host");
		}

